// The token radar's model (radar-2): one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and ranks
// EVERY rankable pre-token protocol in the snapshot: the early rows the radar exists to find. A
// protocol is pre-token when its index entry records no token (no market cap, no CoinGecko id, no
// symbol); the snapshot's live-token protocols are kept apart and shown as the market's own values,
// never mixed into the ranked board — and they calibrate the model.
//
// Implied value follows only from the snapshot's own figures, in four factors:
//
//   category multiple = the median market-cap/TVL of the LIVE protocols in the same category,
//                       computed from this snapshot (fallback: the median over all live protocols
//                       when a category has fewer than 3 live members; clamped to [0.02, 2.0]).
//                       The market itself prices Dexs near 0.34x TVL and Lending near 0.13x: the
//                       model reads that off the snapshot instead of guessing one flat multiple.
//   base              = tvl_usd x category multiple
//   growth            = log-dampened 7-day change: 1 + GROWTH_WEIGHT x sign(g) x ln(1+|g|)/ln(201),
//                       with g clamped to [-60, +200]. A +4448% week is a data spike, not a 45x
//                       company; the log keeps extreme weeks from swamping the board.
//   maturity          = 0.55 + 0.45 x (1 - exp(-age_days/365)): an S-curve. A protocol earns most
//                       of its maturity in its first year; after two years without a token it is
//                       as seasoned as the curve gets. Unknown age uses the snapshot's median age.
//   breadth           = 1 + 0.03 x min(chains-1, 7): a small premium for protocols live on more
//                       chains, capped at +21%.
//   implied           = max(1, round(base x growth x maturity x breadth))
//
// No protocol name is ever special-cased: the same function scores every row, and every constant is
// stated in the dashboard and changeable in the model sandbox.

